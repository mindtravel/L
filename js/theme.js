/* =====================================================================
 * 直角 · 主题
 * ---------------------------------------------------------------------
 * 显示名、配色、尺寸、动画时长 —— 全部集中在这一个文件。
 * 想换名字 / 换配色，只改这里，别处不用动。
 * ===================================================================== */
(function (root) {
  'use strict';

  var ZJ = root.ZJ = root.ZJ || {};

  ZJ.theme = {
    /* ★ 换名字只改这一行 ★ —— 同时更新浏览器标签与页眉标题 */
    name: 'L',

    players: ['黑方', '白方'],

    /* 只有黑白灰：双方靠「实心 / 空心」区分，不靠颜色 */
    paper: '#ffffff',
    ink: '#111111',
    ink2: '#6f6f6f',

    gridMinor: '#f1f1f1',            // 细格线
    gridMajor: '#e2e2e2',            // 每 3 格一根稍重的线
    cross: '#e4e4e4',                // 格点小十字
    crossHot: 'rgba(17,17,17,.46)',  // 可落子的格点：同一个十字，画深画长

    wrap: 0.62,                      // 棋盘外那圈「首尾相接」预览的宽度（单位：格）
    wrapAlpha: 0.42,                 // 环绕副本的淡度

    /* 动画时长（毫秒） */
    dur: {
      edge: 200,        // 线段折出来
      seedRing: 520,    // 种子落子涟漪
      glow: 700,        // 终局逐格亮起
      sparks: 1000,     // 终局粒子
      winPulse: 4600,   // 终局高亮持续
      lastMove: 700,    // 刚落子那一笔的光晕
      wake: 380         // 一次交互之后保持重绘的时长
    },

    /* 特效色：黑方用黑，白方用中灰（纯白在纸上不可见） */
    inkOf: function (p, a) {
      return p === 0 ? 'rgba(17,17,17,' + a + ')' : 'rgba(120,120,120,' + a + ')';
    }
  };
})(typeof window !== 'undefined' ? window : globalThis);
